def main():
    """Main validation workflow"""

    # Parse command line arguments
    parser = argparse.ArgumentParser(description='Validate SMURF results against ground truth')
    parser.add_argument('--smurf_dir', type=str,
                       default='smurf_result',
                       help='Path to SMURF results directory')
    parser.add_argument('--pseudo_hd_dir', type=str,
                       default='pseudo_visium_hd_outpu_full',
                       help='Path to pseudo Visium HD output directory')
    parser.add_argument('--pixel_file', type=str,
                       default='cellpose_sam_human_kidney_output/cropped_visium_hd_human_kidney_pixel_to_cell_mapping_expanded.csv.gz',
                       help='Path to pixel-to-cell mapping CSV (gzipped)')
    parser.add_argument('--sc_h5_file', type=str,
                       default='kidney_sc_data/KIRC_GSE159115_expression.h5',
                       help='Path to single-cell H5 expression file')
    parser.add_argument('--sc_meta_file', type=str,
                       default='kidney_sc_data/KIRC_GSE159115_CellMetainfo_table.tsv',
                       help='Path to single-cell metadata TSV file')
    parser.add_argument('--output_dir', type=str,
                       default='smurf_validation_output',
                       help='Output directory for validation results')
    args = parser.parse_args()

    logger.info("="*80)
    logger.info("SMURF Results Validation")
    logger.info("="*80)

    # Paths from arguments
    smurf_dir = Path(args.smurf_dir)
    pseudo_hd_dir = Path(args.pseudo_hd_dir)
    output_dir = Path(args.output_dir)

    # File paths
    gt_file = pseudo_hd_dir / 'ground_truth_cell_assignments.csv'
    pixel_file = Path(args.pixel_file)
    sc_h5_path = Path(args.sc_h5_file)
    sc_metadata_path = Path(args.sc_meta_file)

    # Step 1: Load SMURF results (now includes nuclear bins!)
    pixels_cells, adata_smurf, segmentation_final, smurf_nuclear_bins, smurf_all_bins = load_smurf_results(smurf_dir)

    # Step 2: Load ground truth
    df_gt, df_pixels, adata_sc_gt = load_ground_truth(gt_file, pixel_file, sc_h5_path, sc_metadata_path)

    # Step 3: Build spatial regions (both nuclear and whole cell)
    gt_nuclear_regions, gt_whole_regions = build_ground_truth_cell_regions(df_pixels)
    smurf_nuclear_regions, smurf_whole_regions = get_smurf_cell_regions(smurf_nuclear_bins, smurf_all_bins)

    # Step 4: Match cells based on NUCLEAR overlap - ANY overlap counts as ground truth match
    cell_matches, match_df = match_cells_by_nuclear_overlap(
        gt_nuclear_regions, smurf_nuclear_regions,
        overlap_threshold=0.0  # Changed from 0.5: any nuclear bin overlap = correct match
    )

    # Step 4.5: Assign ground truth annotations to matched SMURF cells
    adata_smurf_annotated, annotation_df = assign_ground_truth_annotations(
        cell_matches, df_gt, adata_smurf
    )

    # Step 5: Calculate WHOLE CELL spatial overlap for validation
    df_overlap = calculate_spatial_overlap(gt_whole_regions, smurf_whole_regions, cell_matches)

    # Step 6: Calculate gene correlation
    df_corr = calculate_gene_correlation(df_gt, adata_sc_gt, adata_smurf, df_overlap)

    # Step 7: Create overlay visualization (skip if no matches to save time)
    if len(cell_matches) > 0:
        create_overlay_visualization(df_pixels, pixels_cells, segmentation_final, cell_matches, df_overlap, output_dir)
    else:
        logger.warning("="*80)
        logger.warning("WARNING: No cells matched! Skipping overlay visualization.")
        logger.warning("This means nuclear matching completely failed.")
        logger.warning("Check the log above for reasons (coordinate mismatch, missing nuclear data, etc.)")
        logger.warning("="*80)

    # Step 8: Generate validation report
    generate_validation_report(df_overlap, df_corr, output_dir)

    # Step 9: Save annotated SMURF data
    logger.info("Saving annotated SMURF data...")
    # Convert gt_cell_id to string to avoid h5py serialization errors
    adata_smurf_annotated.obs['gt_cell_id'] = adata_smurf_annotated.obs['gt_cell_id'].astype(str)
    adata_smurf_annotated.write(output_dir / 'adata_smurf_annotated.h5ad')
    annotation_df.to_csv(output_dir / 'smurf_cell_annotations.csv', index=False)
    match_df.to_csv(output_dir / 'nuclear_bin_matches.csv', index=False)
    logger.info(f"  Annotated data saved to {output_dir / 'adata_smurf_annotated.h5ad'}")
    logger.info(f"  Annotation table saved to {output_dir / 'smurf_cell_annotations.csv'}")
    logger.info(f"  Match details saved to {output_dir / 'nuclear_bin_matches.csv'}")

    logger.info("="*80)
    logger.info("Validation completed successfully!")
    logger.info(f"Results saved to: {output_dir}")
    logger.info("="*80)


if __name__ == '__main__':
    main()
