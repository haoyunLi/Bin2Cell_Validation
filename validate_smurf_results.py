#!/usr/bin/env python
"""
Validate SMURF Results Against Ground Truth

This script validates SMURF cell segmentation and gene assignment results by comparing:

VALIDATION STRATEGY:
1. Cell Matching: Uses NUCLEAR overlap to match ground truth cells to SMURF cells
   - More accurate because nuclei are distinct and don't overlap
   - Finds best SMURF nucleus for each ground truth nucleus
   - ANY nuclear bin overlap counts as a correct match (ground truth)

2. Spatial Validation: Calculates WHOLE CELL overlap for matched cell pairs
   - Once cells are matched by nuclei, validates the whole cell boundary detection
   - Measures IoU (Intersection over Union) for complete cell regions

3. Gene Correlation: Compares gene expression profiles between matched cells
   - For each matched cell pair, calculates Spearman correlation and RMSE
   - Uses ground truth single-cell expression vs SMURF reconstructed expression
   - Spearman used for both per-cell and gene-wise analysis (rank-based, robust)

SMURF Outputs Used:
- smurf_result/so.pkl: Contains pixels_cells (final whole cell assignments)
- smurf_result/adata_sc_final.h5ad: Final cell-level gene expression data
- smurf_result/segmentation_final.npy: Nuclear segmentation mask (for matching)

Ground Truth Data:
- pseudo_visium_hd_outpu_full/ground_truth_cell_assignments.csv: Maps cell_id -> sc_cell_barcode
- cellpose_sam_human_kidney_output/...pixel_to_cell_mapping_expanded.csv.gz: Maps pixels -> cell_id (with compartment info)
- kidney_sc_data/KIRC_GSE159115_expression.h5: Single-cell ground truth gene expression

Usage:
    python validate_smurf_results.py
"""

