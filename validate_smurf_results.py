def match_cells_by_nuclear_overlap(gt_nuclear_regions, smurf_nuclear_regions, overlap_threshold=0.0):
    """
    Match ground truth cells to SMURF cells based on NUCLEAR overlap.
    This is more accurate because nuclei are distinct and don't overlap.
    OPTIMIZED: Uses sparse matrix multiplication for overlap calculation (10-100x faster!)

    Args:
        overlap_threshold: Minimum overlap ratio to consider a match (default: 0.0 = any overlap)
                          Set to 0.0 to accept any nuclear bin overlap as correct match

    Returns:
        cell_matches: Dictionary mapping gt_cell_id -> (smurf_cell_id, match_metrics)
        match_df: DataFrame with detailed match information
    """
    if overlap_threshold == 0.0:
        logger.info(f"Matching cells based on nuclear overlap (ANY overlap counts as match)...")
    else:
        logger.info(f"Matching cells based on nuclear overlap (threshold: {overlap_threshold})...")

    # Build coordinate -> index mapping (all unique bin coordinates)
    logger.info("  Building coordinate index...")
    all_coords = set()
    for bins in gt_nuclear_regions.values():
        all_coords.update(bins)
    for bins in smurf_nuclear_regions.values():
        all_coords.update(bins)

    coord_to_idx = {coord: i for i, coord in enumerate(all_coords)}
    logger.info(f"    Total unique bin coordinates: {len(all_coords):,}")

    # Get cell ID lists (maintain order)
    gt_cells = [cid for cid in gt_nuclear_regions.keys() if len(gt_nuclear_regions[cid]) > 0]
    smurf_cells = [cid for cid in smurf_nuclear_regions.keys() if len(smurf_nuclear_regions[cid]) > 0]

    logger.info(f"    GT cells with nuclear regions: {len(gt_cells)}")
    logger.info(f"    SMURF cells with nuclear regions: {len(smurf_cells)}")

    # Build sparse matrices (cells × bins)
    # GT matrix
    logger.info("  Building GT sparse matrix...")
    gt_rows, gt_cols = [], []
    for cell_idx, cell_id in enumerate(gt_cells):
        for coord in gt_nuclear_regions[cell_id]:
            gt_rows.append(cell_idx)
            gt_cols.append(coord_to_idx[coord])

    gt_matrix = csr_matrix(
        (np.ones(len(gt_rows), dtype=np.int32), (gt_rows, gt_cols)),
        shape=(len(gt_cells), len(all_coords))
    )
    logger.info(f"    GT matrix: {gt_matrix.shape[0]} cells × {gt_matrix.shape[1]} bins, {gt_matrix.nnz:,} entries")

    # SMURF matrix
    logger.info("  Building SMURF sparse matrix...")
    smurf_rows, smurf_cols = [], []
    for cell_idx, cell_id in enumerate(smurf_cells):
        for coord in smurf_nuclear_regions[cell_id]:
            smurf_rows.append(cell_idx)
            smurf_cols.append(coord_to_idx[coord])

    smurf_matrix = csr_matrix(
        (np.ones(len(smurf_rows), dtype=np.int32), (smurf_rows, smurf_cols)),
        shape=(len(smurf_cells), len(all_coords))
    )
    logger.info(f"    SMURF matrix: {smurf_matrix.shape[0]} cells × {smurf_matrix.shape[1]} bins, {smurf_matrix.nnz:,} entries")

    # Compute overlap matrix (SUPER FAST matrix multiplication!)
    # overlap_matrix[i, j] = number of shared bins between gt_cell[i] and smurf_cell[j]
    logger.info("  Computing overlap matrix (sparse matrix multiplication)...")
    overlap_matrix = gt_matrix @ smurf_matrix.T  # This is the magic!
    logger.info(f"    Overlap matrix computed: {overlap_matrix.shape[0]} × {overlap_matrix.shape[1]}")

    # Compute cell sizes (number of bins per cell)
    gt_sizes = np.array([len(gt_nuclear_regions[cell_id]) for cell_id in gt_cells])
    smurf_sizes = np.array([len(smurf_nuclear_regions[cell_id]) for cell_id in smurf_cells])

    # Find best match for each GT cell (vectorized!)
    logger.info(f"  Finding best matches with overlap threshold {overlap_threshold}...")
    cell_matches = {}
    match_results = []

    for gt_idx, gt_cell_id in enumerate(gt_cells):
        # Get all overlaps for this GT cell
        overlaps = overlap_matrix[gt_idx].toarray().flatten()

        if overlaps.max() > 0:
            best_smurf_idx = overlaps.argmax()
            intersection = int(overlaps[best_smurf_idx])

            # Calculate IoU and overlap ratios
            gt_size = gt_sizes[gt_idx]
            smurf_size = smurf_sizes[best_smurf_idx]
            union = gt_size + smurf_size - intersection
            iou = intersection / union if union > 0 else 0

            # Calculate overlap percentages
            overlap_gt = intersection / gt_size if gt_size > 0 else 0  # % of GT covered
            overlap_smurf = intersection / smurf_size if smurf_size > 0 else 0  # % of SMURF covered

            # Use maximum overlap ratio as the match score (if either is >50%, it's a match)
            overlap_score = max(overlap_gt, overlap_smurf)

            # Store match if above threshold
            if overlap_score >= overlap_threshold:
                match_metrics = {
                    'intersection': intersection,
                    'gt_size': gt_size,
                    'smurf_size': smurf_size,
                    'union': union,
                    'iou': iou,
                    'overlap_gt': overlap_gt,
                    'overlap_smurf': overlap_smurf,
                    'overlap_score': overlap_score
                }
                cell_matches[gt_cell_id] = (smurf_cells[best_smurf_idx], match_metrics)

                match_results.append({
                    'gt_cell_id': gt_cell_id,
                    'smurf_cell_id': smurf_cells[best_smurf_idx],
                    'matched': True,
                    'intersection_bins': intersection,
                    'gt_nuclear_bins': gt_size,
                    'smurf_nuclear_bins': smurf_size,
                    'iou': iou,
                    'overlap_gt_pct': overlap_gt * 100,
                    'overlap_smurf_pct': overlap_smurf * 100,
                    'overlap_score': overlap_score
                })
            else:
                # No match (below threshold)
                match_results.append({
                    'gt_cell_id': gt_cell_id,
                    'smurf_cell_id': None,
                    'matched': False,
                    'intersection_bins': 0,
                    'gt_nuclear_bins': gt_size,
                    'smurf_nuclear_bins': 0,
                    'iou': 0,
                    'overlap_gt_pct': 0,
                    'overlap_smurf_pct': 0,
                    'overlap_score': 0
                })
        else:
            # No overlap at all
            match_results.append({
                'gt_cell_id': gt_cell_id,
                'smurf_cell_id': None,
                'matched': False,
                'intersection_bins': 0,
                'gt_nuclear_bins': gt_sizes[gt_idx],
                'smurf_nuclear_bins': 0,
                'iou': 0,
                'overlap_gt_pct': 0,
                'overlap_smurf_pct': 0,
                'overlap_score': 0
            })

        if (gt_idx + 1) % 1000 == 0:
            logger.info(f"    Processed {gt_idx+1}/{len(gt_cells)} GT cells...")

    match_df = pd.DataFrame(match_results)
    matched = match_df[match_df['matched']]

    logger.info(f"  Matched {len(cell_matches)} cell pairs (overlap >= {overlap_threshold})")
    logger.info(f"  Match rate: {len(cell_matches) / len(gt_cells) * 100:.1f}%")
    if len(matched) > 0:
        logger.info(f"  Average IoU for matches: {matched['iou'].mean():.3f}")
        logger.info(f"  Average GT overlap: {matched['overlap_gt_pct'].mean():.1f}%")
        logger.info(f"  Average SMURF overlap: {matched['overlap_smurf_pct'].mean():.1f}%")

    return cell_matches, match_df


def calculate_spatial_overlap(gt_whole_regions, smurf_whole_regions, cell_matches):
    """
    Calculate spatial overlap for WHOLE CELL regions (for validation).
    Uses the cell matches determined by nuclear overlap.

    Returns:
        overlap_results: DataFrame with columns:
            - gt_cell_id
            - smurf_cell_id (matched based on nuclear overlap)
            - nuclear_match: whether cells were matched
            - iou: Intersection over Union
            - f1_score: F1 score (harmonic mean of precision and recall)
            - precision: intersection / smurf_cell_size
            - recall: intersection / gt_cell_size
    """
    logger.info("Calculating whole-cell spatial overlap for matched cells...")

    results = []

    for gt_cell_id, gt_bins in gt_whole_regions.items():
        match_info = cell_matches.get(gt_cell_id)

        if match_info is not None:
            smurf_cell_id, match_metrics = match_info
            if smurf_cell_id in smurf_whole_regions:
                smurf_bins = smurf_whole_regions[smurf_cell_id]

                intersection = len(gt_bins & smurf_bins)
                union = len(gt_bins | smurf_bins)
                iou = intersection / union if union > 0 else 0

                # Calculate precision and recall as ratios (0-1)
                precision = intersection / len(smurf_bins) if len(smurf_bins) > 0 else 0
                recall = intersection / len(gt_bins) if len(gt_bins) > 0 else 0

                # Calculate F1 score
                f1_score = 2 * (precision * recall) / (precision + recall) if (precision + recall) > 0 else 0

                results.append({
                    'gt_cell_id': gt_cell_id,
                    'smurf_cell_id': smurf_cell_id,
                    'nuclear_match': True,
                    'iou': iou,
                    'f1_score': f1_score,
                    'precision': precision,
                    'recall': recall,
                    'intersection_bins': intersection,
                    'gt_cell_bins': len(gt_bins),
                    'smurf_cell_bins': len(smurf_bins)
                })
            else:
                # No match found
                results.append({
                    'gt_cell_id': gt_cell_id,
                    'smurf_cell_id': None,
                    'nuclear_match': False,
                    'iou': 0,
                    'f1_score': 0,
                    'precision': 0,
                    'recall': 0,
                    'intersection_bins': 0,
                    'gt_cell_bins': len(gt_bins),
                    'smurf_cell_bins': 0
                })
        else:
            # No match found
            results.append({
                'gt_cell_id': gt_cell_id,
                'smurf_cell_id': None,
                'nuclear_match': False,
                'iou': 0,
                'f1_score': 0,
                'precision': 0,
                'recall': 0,
                'intersection_bins': 0,
                'gt_cell_bins': len(gt_bins),
                'smurf_cell_bins': 0
            })

        if len(results) % 1000 == 0:
            logger.info(f"    Processed {len(results)} ground truth cells...")

    df_overlap = pd.DataFrame(results)

    logger.info(f"  Completed spatial overlap calculation for {len(df_overlap)} cells")
    logger.info(f"  Cells with nuclear match: {df_overlap['nuclear_match'].sum()}")
    logger.info(f"  Average whole-cell overlap (IoU): {df_overlap[df_overlap['nuclear_match']]['iou'].mean():.4f}")
    logger.info(f"  Average F1 score: {df_overlap[df_overlap['nuclear_match']]['f1_score'].mean():.3f}")

    return df_overlap


def calculate_gene_correlation(df_gt, adata_sc_gt, adata_smurf, df_overlap):
    """
    Calculate gene expression correlation between ground truth and SMURF cells.

    For each matched cell pair (gt_cell -> smurf_cell), compute:
    - Spearman correlation of gene expression (rank-based, robust to scale differences)
    - RMSE (Root Mean Squared Error)

    Returns:
        correlation_results: DataFrame with correlation metrics per cell
    """
    logger.info("Calculating gene expression correlation...")

    # Filter to only cells with spatial matches
    df_matched = df_overlap[df_overlap['smurf_cell_id'].notna()].copy()
    logger.info(f"  Analyzing {len(df_matched)} matched cell pairs")

    # Build mapping from gt_cell_id to sc_cell_barcode
    gt_cell_to_barcode = df_gt.set_index('cell_id')['sc_cell_barcode'].to_dict()

    results = []

    # Track filtering reasons
    filter_counts = {
        'no_barcode_mapping': 0,
        'barcode_not_in_sc_data': 0,
        'smurf_idx_out_of_range': 0,
        'gene_length_mismatch': 0,
        'zero_variance': 0,
        'success': 0
    }

    # Get common genes ONCE (same for all cells)
    common_genes = list(set(adata_sc_gt.var_names) & set(adata_smurf.var_names))
    logger.info(f"  Found {len(common_genes)} common genes between GT and SMURF")

    if len(common_genes) < 10:
        logger.warning(f"  Too few common genes ({len(common_genes)}), skipping correlation analysis")
        return pd.DataFrame()

    # Vectorized iteration (100x faster than iterrows!)
    for idx in range(len(df_matched)):
        gt_cell_id = df_matched.iloc[idx]['gt_cell_id']
        smurf_cell_id = df_matched.iloc[idx]['smurf_cell_id']

        # Get ground truth single-cell barcode
        if gt_cell_id not in gt_cell_to_barcode:
            filter_counts['no_barcode_mapping'] += 1
            continue

        sc_barcode = gt_cell_to_barcode[gt_cell_id]

        # Get gene expression from ground truth single cell
        if sc_barcode not in adata_sc_gt.obs_names:
            filter_counts['barcode_not_in_sc_data'] += 1
            continue

        # Get gene expression from SMURF cell
        # SMURF cell IDs are NOT sequential (e.g., 5, 7, 11, ..., 155702)
        # They're stored as strings with .0 suffix in obs_names
        smurf_cell_key = f"{int(smurf_cell_id)}.0"
        if smurf_cell_key not in adata_smurf.obs_names:
            filter_counts['smurf_idx_out_of_range'] += 1
            continue

        # Extract expression for common genes (ensure same order!)
        gt_expr = adata_sc_gt[sc_barcode, common_genes].X.toarray().flatten()
        # Get SMURF expression in the same gene order as GT
        smurf_expr = adata_smurf[smurf_cell_key, common_genes].X.toarray().flatten()

        # Verify same length (sanity check)
        if len(gt_expr) != len(smurf_expr):
            logger.warning(f"    Gene length mismatch for cell {gt_cell_id}: GT={len(gt_expr)}, SMURF={len(smurf_expr)}")
            filter_counts['gene_length_mismatch'] += 1
            continue

        # Calculate correlations and RMSE (Spearman only for per-cell, since GT=raw vs SMURF=normalized)
        if len(gt_expr) > 0 and len(smurf_expr) > 0 and np.std(gt_expr) > 0 and np.std(smurf_expr) > 0:
            spearman_corr, spearman_pval = spearmanr(gt_expr, smurf_expr)

            # Calculate RMSE (Root Mean Squared Error)
            rmse = np.sqrt(np.mean((gt_expr - smurf_expr) ** 2))

            results.append({
                'gt_cell_id': gt_cell_id,
                'smurf_cell_id': smurf_cell_id,
                'sc_barcode': sc_barcode,
                'spearman_corr': spearman_corr,
                'spearman_pval': spearman_pval,
                'rmse': rmse,
                'n_common_genes': len(common_genes),
                'gt_mean_expr': np.mean(gt_expr),
                'smurf_mean_expr': np.mean(smurf_expr)
            })
            filter_counts['success'] += 1
        else:
            filter_counts['zero_variance'] += 1

        if len(results) % 100 == 0:
            logger.info(f"    Processed {len(results)} cell pairs...")

    df_corr = pd.DataFrame(results)

    logger.info(f"  Completed correlation analysis for {len(df_corr)} cell pairs")
    logger.info(f"  ")
    logger.info(f"  Filtering breakdown:")
    logger.info(f"    Started with: {len(df_matched)} spatially matched cell pairs")
    logger.info(f"    Successfully calculated: {filter_counts['success']} ({filter_counts['success']/len(df_matched)*100:.1f}%)")
    logger.info(f"    Filtered out:")
    logger.info(f"      - No barcode mapping in ground_truth_cell_assignments.csv: {filter_counts['no_barcode_mapping']}")
    logger.info(f"      - Barcode not found in single-cell reference data: {filter_counts['barcode_not_in_sc_data']}")
    logger.info(f"      - SMURF cell index out of range: {filter_counts['smurf_idx_out_of_range']}")
    logger.info(f"      - Gene length mismatch: {filter_counts['gene_length_mismatch']}")
    logger.info(f"      - Zero variance in expression: {filter_counts['zero_variance']}")

    if len(df_corr) > 0:
        logger.info(f"  Average Spearman correlation: {df_corr['spearman_corr'].mean():.3f}")
        logger.info(f"  Average RMSE: {df_corr['rmse'].mean():.3f}")

    return df_corr


def assign_ground_truth_annotations(cell_matches, df_gt, adata_smurf):
    """
    Assign ground truth cell type and barcode to matched SMURF cells.

    Args:
        cell_matches: Dict mapping gt_cell_id -> (smurf_cell_id, match_metrics)
        df_gt: Ground truth DataFrame with cell_id, sc_cell_barcode, cell_type
        adata_smurf: SMURF AnnData object

    Returns:
        adata_smurf_annotated: SMURF AnnData with GT annotations in .obs
        annotation_df: DataFrame with smurf_cell_id -> gt_cell_type, gt_barcode mapping
    """
    logger.info("Assigning ground truth annotations to matched SMURF cells...")

    # Build mapping from gt_cell_id to annotations
    gt_annotations = df_gt.set_index('cell_id')[['sc_cell_barcode', 'cell_type']].to_dict('index')

    annotation_results = []

    for gt_cell_id, (smurf_cell_id, metrics) in cell_matches.items():
        if gt_cell_id in gt_annotations:
            gt_info = gt_annotations[gt_cell_id]

            annotation_results.append({
                'smurf_cell_id': smurf_cell_id,
                'gt_cell_id': gt_cell_id,
                'gt_cell_type': gt_info['cell_type'],
                'gt_barcode': gt_info['sc_cell_barcode'],
                'match_quality_iou': metrics['iou'],
                'match_quality_overlap': metrics['overlap_score']
            })

    annotation_df = pd.DataFrame(annotation_results)

    logger.info(f"  Annotated {len(annotation_df)} SMURF cells with ground truth information")

    if len(annotation_df) > 0:
        logger.info(f"  Cell type distribution in matched cells:")
        for cell_type, count in annotation_df['gt_cell_type'].value_counts().items():
            logger.info(f"    {cell_type}: {count}")

    # Add annotations to SMURF AnnData
    adata_smurf_annotated = adata_smurf.copy()

    # Initialize annotation columns
    adata_smurf_annotated.obs['gt_cell_id'] = None
    adata_smurf_annotated.obs['gt_cell_type'] = 'unmatched'
    adata_smurf_annotated.obs['gt_barcode'] = None
    adata_smurf_annotated.obs['match_quality_iou'] = 0.0
    adata_smurf_annotated.obs['match_quality_overlap'] = 0.0

    # Assign annotations (SMURF cells are 1-indexed)
    for _, row in annotation_df.iterrows():
        smurf_idx = int(row['smurf_cell_id']) - 1
        if 0 <= smurf_idx < adata_smurf_annotated.n_obs:
            adata_smurf_annotated.obs.iloc[smurf_idx, adata_smurf_annotated.obs.columns.get_loc('gt_cell_id')] = row['gt_cell_id']
            adata_smurf_annotated.obs.iloc[smurf_idx, adata_smurf_annotated.obs.columns.get_loc('gt_cell_type')] = row['gt_cell_type']
            adata_smurf_annotated.obs.iloc[smurf_idx, adata_smurf_annotated.obs.columns.get_loc('gt_barcode')] = row['gt_barcode']
            adata_smurf_annotated.obs.iloc[smurf_idx, adata_smurf_annotated.obs.columns.get_loc('match_quality_iou')] = row['match_quality_iou']
            adata_smurf_annotated.obs.iloc[smurf_idx, adata_smurf_annotated.obs.columns.get_loc('match_quality_overlap')] = row['match_quality_overlap']

    return adata_smurf_annotated, annotation_df


def create_overlay_visualization(df_pixels, pixels_cells, segmentation_final, cell_matches, df_overlap, output_dir, microns_per_pixel=0.2739038899725172, sample_region=None):
    """
    Create overlay visualization of ground truth and SMURF segmentations.
    Shows matched cells, unmatched cells, and overlap quality.

    Args:
        df_pixels: Ground truth pixel-to-cell mapping
        pixels_cells: SMURF whole cell segmentation
        segmentation_final: SMURF nuclear segmentation
        cell_matches: Dictionary mapping gt_cell_id -> smurf_cell_id
        df_overlap: DataFrame with overlap metrics
        output_dir: Output directory
        sample_region: Optional (x_min, x_max, y_min, y_max) to zoom into a region
    """
    logger.info("Creating overlay visualizations...")
    output_path = Path(output_dir)
    output_path.mkdir(exist_ok=True)

    # Build ground truth segmentation mask at pixel level
    logger.info("  Building ground truth segmentation mask...")
    gt_mask = np.zeros(pixels_cells.shape, dtype=np.int32)

    # Use chunked processing for large dataframe
    chunk_size = 1000000
    for start_idx in range(0, len(df_pixels), chunk_size):
        end_idx = min(start_idx + chunk_size, len(df_pixels))
        chunk = df_pixels.iloc[start_idx:end_idx]

        # Filter to cells only
        chunk_cells = chunk[chunk['cell_id'] > 0]
        if len(chunk_cells) > 0:
            x_coords = chunk_cells['x'].values
            y_coords = chunk_cells['y'].values
            cell_ids = chunk_cells['cell_id'].values

            # Bounds check
            valid = (y_coords >= 0) & (y_coords < gt_mask.shape[0]) & (x_coords >= 0) & (x_coords < gt_mask.shape[1])
            gt_mask[y_coords[valid], x_coords[valid]] = cell_ids[valid]

        if (start_idx + chunk_size) % 5000000 == 0:
            logger.info(f"    Processed {start_idx + chunk_size:,} pixels...")

    # Use full resolution - no cropping!
    logger.info(f"  Creating full resolution overlay: {gt_mask.shape}")
    gt_crop = gt_mask
    smurf_crop = pixels_cells
    nuclear_crop = segmentation_final

    # Create color-coded overlay - FULLY VECTORIZED (100x faster!)
    logger.info("  Creating fully vectorized overlay...")

    # Create RGB image
    overlay = np.zeros((*gt_crop.shape, 3), dtype=np.uint8)

    # Simple 2-color overlay: GT in green, SMURF in red, overlap in yellow
    # This is FULLY vectorized - no loops!
    gt_mask = (gt_crop > 0)
    smurf_mask = (smurf_crop > 0)

    # Green channel: Ground truth
    overlay[gt_mask, 1] = 255

    # Red channel: SMURF
    overlay[smurf_mask, 0] = 255

    # Where both overlap, you get yellow (red + green = yellow)
    # Where only GT: green
    # Where only SMURF: red

    logger.info("  Overlay created (Green=GT, Red=SMURF, Yellow=Overlap)")

    # Save as a single full-resolution image (no matplotlib, direct image save)
    logger.info("  Saving full resolution overlay image...")
    from PIL import Image

    # Convert to PIL Image and save at original resolution
    overlay_img = Image.fromarray(overlay)
    overlay_path = output_path / 'segmentation_overlay_full_resolution.png'
    overlay_img.save(overlay_path, compress_level=6)  # PNG compression

    logger.info(f"  Saved full resolution overlay: {overlay_path}")
    logger.info(f"  Image size: {overlay.shape[1]} x {overlay.shape[0]} pixels")

    # Also save a legend as a separate small image
    fig, ax = plt.subplots(figsize=(6, 3))
    ax.axis('off')

    from matplotlib.patches import Patch
    legend_elements = [
        Patch(facecolor='yellow', label='Overlap (GT + SMURF agree)'),
        Patch(facecolor='green', label='Ground Truth only'),
        Patch(facecolor='red', label='SMURF only'),
        Patch(facecolor='black', label='Background (no cells)')
    ]
    legend = ax.legend(handles=legend_elements, loc='center', fontsize=14, frameon=True)
    ax.set_title('Overlay Color Legend', fontsize=16, fontweight='bold', pad=20)

    plt.tight_layout()
    plt.savefig(output_path / 'overlay_legend.png', dpi=150, bbox_inches='tight')
    plt.close()

    logger.info(f"  Saved legend to {output_path / 'overlay_legend.png'}")


